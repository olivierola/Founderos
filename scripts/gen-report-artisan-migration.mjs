// Generates the Report Artisan migration from report-artisan-src/.
//
// Two things travel out of that folder and into the database:
//
//   assets/  — the report engine (CSS, runtime, Editor.js bundle, HTML shell),
//     ~450 kB of static text an edge function has to read at build time.
//     Bundling it into _shared would push those 450 kB into EVERY function that
//     imports the agent toolset, so it lives in a table instead.
//
//   references/ — the skill's playbooks, one agent_skill_files row each, pulled
//     on demand with read_skill_file rather than carried in context.
//
// Editing either: change the file in report-artisan-src/ (the CSS tokens at the
// top of report.css are the branding knobs), re-run this script, and apply the
// regenerated migration. That folder is the source of truth — nothing here is
// authored in SQL. It lives at the root rather than under skills_repo/ because
// skills_repo is gitignored (it holds upstream clones), and a source a fresh
// checkout does not have is a migration nobody can regenerate.
//
// The skill's own prose (its system_prompt_extension) is NOT generated: it lives
// in 0206 because the FounderOS version writes through tools instead of the
// upstream skill's python build step. content-schema.md carries the same
// adaptation; the pristine upstream archive is report-artisan.skill at the root.
//
// Run:  node scripts/gen-report-artisan-migration.mjs
import { readFileSync, writeFileSync, statSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const SKILL = join(ROOT, "report-artisan-src");
// The engine is seeded by migration, so a CHANGE to it needs a NEW migration:
// `supabase db push` never re-runs a file it has already applied. Pass the
// target name, and --only to ship just the assets that actually moved (the
// Editor.js vendor bundle is 356 of the 443 kB and rarely changes).
//
//   node scripts/gen-report-artisan-migration.mjs --out=0209_engine_v2.sql --only=report.css,runtime.js
const arg = (k, d) => (process.argv.find((a) => a.startsWith(`--${k}=`)) ?? `--${k}=${d}`).split("=").slice(1).join("=");
const OUT_NAME = arg("out", "0207_report_artisan_assets.sql");
const ONLY = arg("only", "").split(",").map((x) => x.trim()).filter(Boolean);
const OUT = join(ROOT, "supabase", "migrations", OUT_NAME);

const ASSETS = [
  { name: "report.css", path: join(SKILL, "assets", "report.css") },
  { name: "runtime.js", path: join(SKILL, "assets", "runtime.js") },
  { name: "shell.html", path: join(SKILL, "assets", "shell.html") },
  { name: "editorjs.bundle.js", path: join(SKILL, "scripts", "vendor", "editorjs.bundle.js") },
];

// Order matters: it is the order they appear in the skill's file list, and the
// order the agent meets them in.
const FILE_ORDER = ["content-schema.md", "charts.md", "gallery.md"];

const TAG = "$RA_ASSET$";

// SQL string literal — NOT JSON.stringify: double quotes are identifiers in SQL.
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const quote = (name, content) => {
  if (content.includes(TAG)) {
    throw new Error(`${name} contains the dollar-quote tag ${TAG} — pick another tag.`);
  }
  return `${TAG}${content}${TAG}`;
};

const rows = ASSETS
  .filter(({ name }) => ONLY.length === 0 || ONLY.includes(name))
  .map(({ name, path }) => ({
    name,
    content: readFileSync(path, "utf8"),
    bytes: statSync(path).size,
  }));

const refDir = join(SKILL, "references");
const refs = readdirSync(refDir)
  .filter((f) => f.endsWith(".md"))
  .sort((a, b) => {
    const ia = FILE_ORDER.indexOf(a), ib = FILE_ORDER.indexOf(b);
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.localeCompare(b);
  })
  .map((f, i) => ({ path: f, content: readFileSync(join(refDir, f), "utf8"), sort: i }));

const total = rows.reduce((n, r) => n + r.bytes, 0);

const sql = `-- ${OUT_NAME}
--
-- GENERATED by scripts/gen-report-artisan-migration.mjs — do not edit by hand.
-- Source: report-artisan-src/ (${(total / 1024).toFixed(0)} kB of engine,
-- ${refs.length} playbooks).

-- ── Le moteur ───────────────────────────────────────────────────────────────
-- ${rows.length === ASSETS.length
    ? "Les quatre fichiers qu'un rapport construit inline."
    : `Les fichiers du moteur qui ont changé : ${rows.map((r) => r.name).join(", ")}.`}
-- En lignes plutôt qu'en module partagé pour ne pas traîner 450 ko dans le
-- bundle de chaque edge function, et plutôt qu'en objets storage pour qu'un
-- environnement neuf soit complet après \`supabase db push\`, sans téléversement.

insert into public.report_artisan_assets (name, content) values
${rows.map((r) => `  (${lit(r.name)}, ${quote(r.name, r.content)})`).join(",\n")}
on conflict (name) do update set content = excluded.content, updated_at = now();

-- ── Les fiches du skill ─────────────────────────────────────────────────────
-- Lues à la demande avec read_skill_file(slug="report-artisan", path="…").

delete from public.agent_skill_files f
using public.agent_skills s
where s.id = f.skill_id and s.workspace_id is null and s.slug = 'report-artisan';

insert into public.agent_skill_files (skill_id, path, content, sort)
select s.id, v.path, v.content, v.sort
from public.agent_skills s
cross join (values
${refs.map((r) => `  (${lit(r.path)}, ${quote(r.path, r.content)}, ${r.sort})`).join(",\n")}
) as v(path, content, sort)
where s.workspace_id is null and s.slug = 'report-artisan';
`;

writeFileSync(OUT, sql, "utf8");
console.log(
  `${OUT}\n  ${rows.map((r) => `${r.name} ${(r.bytes / 1024).toFixed(0)} kB`).join(" · ")}`
  + `\n  ${refs.map((r) => r.path).join(" · ")}\n  total ${(total / 1024).toFixed(0)} kB`,
);
